for lang, add in (("fr", FR), ("en", EN), ("ar", AR), ("es", ES)):
    missing = set(FR) - set(add)
    assert not missing, f"{lang} manque : {missing}"
    before = len(data[lang])
    data[lang].update(add)
    print(f"{lang}: {before} -> {len(data[lang])} clés")

# Parité stricte
keys = {k: set(d) for k, d in data.items()}
assert keys["fr"] == keys["en"] == keys["ar"] == keys["es"], "parité rompue"
P.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
